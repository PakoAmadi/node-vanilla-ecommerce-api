'use strict';

const test = require('node:test');
const assert = require('node:assert');
require('../src/config/env')();

const db = require('../src/database/db');

test('PostgreSQL Database Module Integration', async (t) => {

  t.before(async () => {
    await db.connect();
  });

  t.after(async () => {
    await db.disconnect();
  });

  await t.test('should successfully establish connection and verify schema creation', async () => {
    // Check whether the “users” table exists in the “public” schema
    const checkTableQuery = `
            SELECT EXISTS (
            SELECT FROM information_schema.tables 
            WHERE table_schema = 'public' AND table_name = 'users'
          );
        `;
    const result = await db.query(checkTableQuery);

    // The result is returned as an array of rows
    assert.strictEqual(result.rows[0].exists, true);
  });

  await t.test('should successfully execute queries inside a safe transaction rollback', async () => {
    // We start a transaction so that the changes are not physically written to the database
    await db.query('BEGIN');

    try {
      const mockUser = {
        name: 'Test Testerson',
        email: 'integration-test@example.com',
        password: 'hashed_password_abc_123'
      };

      // Let's try inserting a test entry
      const insertQuery = `
                INSERT INTO users (name, email, password) 
                VALUES ($1, $2, $3) 
                RETURNING id, name, email;
            `;

      const insertResult = await db.query(insertQuery, [mockUser.name, mockUser.email, mockUser.password]);

      //  We check that the record returned the ID generated by the database
      assert.ok(insertResult.rows[0].id);
      assert.strictEqual(insertResult.rows[0].name, mockUser.name);
      assert.strictEqual(insertResult.rows[0].email, mockUser.email);

      // We're checking to make sure the B-tree index for email works quickly (the query finds the user)
      const selectResult = await db.query('SELECT name FROM users WHERE email = $1', [mockUser.email]);
      assert.strictEqual(selectResult.rows.length, 1);
      assert.strictEqual(selectResult.rows[0].name, mockUser.name);

    } finally {
      // We always roll back the changes, the test finishes, and the database remains clean
      await db.query('ROLLBACK');
    }
  });

  await t.test('should enforce unique constraints on email column', async () => {
    await db.query('BEGIN');

    try {
      const insertQuery = 'INSERT INTO users (name, email, password) VALUES ($1, $2, $3);';

      // Let's insert the first record—everything should go smoothly
      await db.query(insertQuery, ['User One', 'unique@example.com', 'password']);

      // We're trying to enter the exact same email address again
      await assert.rejects(
        async () => {
          await db.query(insertQuery, ['User Two', 'unique@example.com', 'password']);
        },
        (err) => {
          // PostgreSQL returns error code ‘23505’ for a violation of a UNIQUE constraint
          return err.code === '23505';
        }
      );

    } finally {
      await db.query('ROLLBACK');
    }
  });

})
